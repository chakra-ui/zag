import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

// Writes the doc key unions so @zag-js/docs declarations don't depend on its JSON
const dataDir = join(process.cwd(), "packages", "docs", "data")
const outPath = join(process.cwd(), "packages", "docs", "src", "keys.ts")

const sources = {
  ApiDocKey: "api.json",
  AccessibilityDocKey: "accessibility.json",
  CssVarDocKey: "css-vars.json",
  DataAttrDocKey: "data-attr.json",
}

const lines = Object.entries(sources).map(([name, file]) => {
  const keys = Object.keys(JSON.parse(readFileSync(join(dataDir, file), "utf-8")))
  return `export type ${name} =\n${keys.map((key) => `  | ${JSON.stringify(key)}`).join("\n")}\n`
})

writeFileSync(outPath, `// Generated by scripts/docs-keys.ts. Do not edit.\n\n${lines.join("\n")}`)
