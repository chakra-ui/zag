import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dirname, "..")
const out = join(root, "skills/zag/references/components.md")

interface Doc {
  slug: string
  title: string
  description: string
  package: string
}

function readFrontmatter(file: string): Record<string, string> {
  const match = readFileSync(file, "utf8").match(/^---\n([\s\S]*?)\n---/)
  const fields: Record<string, string> = {}
  let key = ""
  for (const line of match?.[1].split("\n") ?? []) {
    const field = line.match(/^(\w+):\s*(.*)$/)
    if (field) {
      key = field[1]
      fields[key] = field[2]
    } else if (key) {
      fields[key] += ` ${line.trim()}`
    }
  }
  for (const k in fields) fields[k] = fields[k].trim().replace(/^"|"$/g, "")
  return fields
}

function readDocs(dir: string): Doc[] {
  return readdirSync(join(root, dir))
    .filter((file) => file.endsWith(".mdx"))
    .map((file) => {
      const fields = readFrontmatter(join(root, dir, file))
      return {
        slug: file.replace(".mdx", ""),
        title: fields.title,
        description: fields.description,
        package: fields.package,
      }
    })
    .sort((a, b) => a.title.localeCompare(b.title))
}

const row = (doc: Doc) => `| ${doc.title} | \`${doc.slug}\` | \`${doc.package ?? ""}\` | ${doc.description ?? ""} |`

const markdown = `<!-- Generated by \`pnpm skill:components\` from website/data. Don't edit by hand. -->

# Components

Each component's docs page, with code for one framework, is at
\`{docs}/components/{framework}/{slug}.md\`. The framework is \`react\`, \`vue\`, \`svelte\` or \`solid\`. Preact uses the
React page.

| Component | Slug | Package | What it is |
| --- | --- | --- | --- |
${readDocs("website/data/components").map(row).join("\n")}

# Utilities

Each utility's page is at \`{docs}/utilities/{slug}.md\`.

| Utility | Slug | Package | What it is |
| --- | --- | --- | --- |
${readDocs("website/data/utilities").map(row).join("\n")}
`

writeFileSync(out, markdown)
console.log(`Wrote ${out}`)
